#!/usr/bin/env bash
# merge-workspaces.sh <directory>
#
# Reads all *.tfvars files directly in <directory> (non-recursive: files in
# subdirectories such as examples/ are never included), strips the outer
# `workspaces = {` / `}` wrapper from each, and merges them
# into a single HCL workspaces map written to stdout.
#
# Usage:
#   bash scripts/merge-workspaces.sh parameters/workspaces \
#     > merged_workspaces.auto.tfvars

set -euo pipefail

directory="${1:?Usage: $0 <workspaces_dir>}"

if ! ls "$directory"/*.tfvars > /dev/null 2>&1; then
  echo "Error: no *.tfvars files found directly in '$directory'." >&2
  echo "Copy a template from '$directory/examples/' into '$directory/' under a new name (examples/ itself is never read)." >&2
  exit 1
fi

echo "# Auto-generated by scripts/merge-workspaces.sh — do not edit manually."
echo "# Source: ${directory}/*.tfvars"
echo ""
echo "workspaces = {"

for file in "$directory"/*.tfvars; do
  filename=$(basename "$file")
  echo ""
  echo "  # ── $filename ─────────────────────────────────────────────────────────"
  # Keep only what sits between the `workspaces = {` line and its closing `}`
  # (the last line that is just `}`); leading comments and trailing blanks are dropped.
  awk '
    { lines[NR] = $0 }
    END {
      start = 0; stop = 0
      for (i = 1; i <= NR; i++) if (!start && lines[i] ~ /^[[:space:]]*workspaces[[:space:]]*=[[:space:]]*\{[[:space:]]*$/) start = i
      for (i = NR; i >= 1; i--) if (lines[i] ~ /^[[:space:]]*\}[[:space:]]*$/) { stop = i; break }
      if (!start || !stop || stop <= start) { print "Error: no `workspaces = { ... }` block in " FILENAME > "/dev/stderr"; exit 1 }
      for (i = start + 1; i < stop; i++) print lines[i]
    }
  ' "$file"
done

echo ""
echo "}"
